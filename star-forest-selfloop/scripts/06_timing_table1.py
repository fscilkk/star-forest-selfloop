"""Table 1: dense eigensolver versus the secular equation (Proposition 5.7).

Members: r = floor(n/12) stars of sizes 1,2,3,4,5 repeated cyclically, w = floor(n/10),
n0 the remaining vertices.  Dense: LAPACK via numpy.linalg.eigvalsh, median of 5 runs.
Secular: bisection in double precision, median of 5 averages over 500 runs, after a warm-up.
Both single-threaded.  The energies and discrepancies are checked against the paper; the
timings are reported only, since they depend on the machine.

Usage:  python 06_timing_table1.py            (full table, about 1 minute)
        python 06_timing_table1.py --quick    (skip n = 2000 and 4000 in the dense column)
"""
import os
import sys

for var in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(var, "1")

from common import check, finish  # noqa: E402

import time  # noqa: E402
import statistics  # noqa: E402
import numpy as np  # noqa: E402

from starforest import adjacency, energy_secular, energy_dense  # noqa: E402

quick = "--quick" in sys.argv


def member(n):
    """(n0, w, {m: nu_m}): r = n//12 stars of sizes 1..5 cyclically, w = n//10."""
    r, w = n // 12, n // 10
    nu = {s: r // 5 + (1 if s - 1 < r % 5 else 0) for s in range(1, 6)}
    nu = {s: v for s, v in nu.items() if v}
    n0 = n - w - sum((s + 1) * v for s, v in nu.items())
    return n0, w, nu


def as_tuple(nu):
    return tuple(s for s in sorted(nu, reverse=True) for _ in range(nu[s]))


def median_dense(n0, w, ms):
    A, _ = adjacency(n0, w, as_tuple(ms))
    times, E = [], None
    for _ in range(5):
        t = time.perf_counter()
        E = energy_dense(A)
        times.append(time.perf_counter() - t)
    return E, statistics.median(times)


def median_secular(n0, w, ms):
    energy_secular(n0, w, ms)                              # warm-up
    avgs = []
    for _ in range(5):
        t = time.perf_counter()
        for _ in range(500):
            E = energy_secular(n0, w, ms)
        avgs.append((time.perf_counter() - t) / 500)
    return E, statistics.median(avgs)


paper = {250: 527.977, 500: 1059.225, 1000: 2124.015, 2000: 4253.311, 4000: 8512.232,
         10**4: 21288.695, 10**6: 2129405.661, 10**8: 212941102.407}

rows = []
print(f"{'n':>10} {'E':>16} {'dense (s)':>10} {'secular (ms)':>13} {'|dense-secular|':>16}")
worst_abs, worst_rel, worst_rel40 = 0.0, 0.0, 0.0
for n, Ep in paper.items():
    n0, w, ms = member(n)
    Es, ts = median_secular(n0, w, ms)
    dense_ok = n <= (1000 if quick else 4000)
    if dense_ok:
        Ed, td = median_dense(n0, w, ms)
        diff = abs(Ed - Es)
        worst_abs = max(worst_abs, diff)
        worst_rel = max(worst_rel, diff / Es)
        print(f"{n:>10} {Es:>16.3f} {td:>10.4f} {1e3 * ts:>13.3f} {diff:>16.1e}")
        rows.append((n, Es, f"{td:.3g}", f"{1e3 * ts:.2f}", diff))
    else:
        E40 = energy_secular(n0, w, ms, mp=True, dps=40)
        rel = float(abs(E40 - Es) / E40)
        if n >= 10**4:
            worst_rel40 = max(worst_rel40, rel)
        print(f"{n:>10} {Es:>16.3f} {'--':>10} {1e3 * ts:>13.3f} {'--':>16}")
        rows.append((n, Es, "--", f"{1e3 * ts:.2f}", None))
    check(f"E at n = {n}", round(Es, 3), Ep)

print()
check("dense and secular energies agree (n <= 4000), relative", f"{worst_rel:.1e}",
      "below 1e-14", ok=worst_rel < 1e-14)
check("double precision vs 40-digit evaluation, n >= 1e4 (relative)", f"{worst_rel40:.1e}",
      "below 1e-15", ok=worst_rel40 < 1e-15)
import platform  # noqa: E402


def tex_n(n):
    return f"$10^{{{len(str(n)) - 1}}}$" if n >= 10**4 else f"${n}$"


def tex_sci(v):
    if v is None:
        return "--"
    mant, ex = f"{v:.1e}".split("e")
    return f"${mant}\\times10^{{{int(ex)}}}$"


os.makedirs(os.path.join("..", "results"), exist_ok=True)
table_name = "table1_quick.tex" if quick else "table1.tex"
with open(os.path.join("..", "results", table_name), "w") as f:
    f.write(f"% generated by scripts/06_timing_table1.py on {platform.platform()}, "
            f"{platform.processor() or 'unknown CPU'}, Python {platform.python_version()}, "
            f"NumPy {np.__version__}\n")
    for n, Es, td, ts_, diff in rows:
        td_tex = "--" if td == "--" else f"${td}$"
        f.write(f"{tex_n(n)} & ${Es:.3f}$ & {td_tex} & ${ts_}$ & {tex_sci(diff)}\\\\\n")
print(f"\nwrote results/{table_name} (rows for the tabular of Table 1)")
print(f"machine: {platform.platform()}; Python {platform.python_version()}; NumPy {np.__version__}")
print("Timings depend on the machine; rerun on your own machine before quoting them.")
finish()
